"""
실습 04: 숫자 데이터 표준화(Standardization)

목적:
train 데이터를 기준으로 평균과 표준편차를 계산하고, 그 기준을 사용해 valid 데이터를 표준화한다.

왜 표준화하는가?
머신러닝에서는 데이터마다 숫자의 크기와 단위가 다를 수 있음.

예시:
- input_chars: 100 ~ 10000
- error_count: 0 ~ 10

이처럼 숫자의 크기가 크게 다르면 일부 머신러닝 모델에서 특정 변수의 영향이 지나치게 커질 수 있음.

따라서 데이터를 평균 0, 표준편차 1을 기준으로 변환함.
"""

# ==========================================================
# 1. 필요한 라이브러리 가져오기
# ==========================================================
# Pandas: 표 형태의 데이터(DataFrame)를 처리하는 라이브러리
import pandas as pd
# StandardScaler:
# scikit-learn에서 제공하는 데이터 표준화 클래스
#
# train 데이터의 평균과 표준편차를 학습하고 해당 기준으로 데이터를 변환하는 역할을 함.
from sklearn.preprocessing import StandardScaler

# ==========================================================
# 2. 학습용(train), 검증용(valid) 데이터 생성
# ==========================================================

# DataFrame: 행과 열로 구성된 2차원 데이터 구조
#
# input_chars라는 열을 생성하고 100, 200, 300을 각 행에 저장함.
#
# train 데이터는 표준화 기준을 계산하는 데 사용함.
train = pd.DataFrame({"input_chars": [100, 200, 300]})

# valid 데이터는 학습에 사용하지 않는 별도의 데이터. 
# 별도로 관리하는 이유는 모델이 처음보는 데이터에도 잘 동작하는지 검증하기 위해서
valid = pd.DataFrame({"input_chars": [400, 500]})

# ==========================================================
# 3. 표준화 객체 생성
# ==========================================================
# StandardScaler 클래스의 인스턴스를 생성함.
# 이 시점에는 아직 평균과 표준편차가 계산되지 않았음.
scaler = StandardScaler()

# ==========================================================
# 4. train 데이터를 기준으로 표준화 규칙 학습
# ==========================================================
# fit():
# 전달받은 데이터에서 평균과 표준편차를 계산하여 저장함.
# train = [100, 200, 300]
# 평균 = (100 + 200 + 300) / 3 = 200
# StandardScaler는 이 평균과 표준편차를 이후 transform()에서 사용할 수 있도록 저장함.
# 주의: fit()은 데이터를 실제로 변환해서 반환하지 않음. 변환 규칙만 학습함.
scaler.fit(train)


# ==========================================================
# 5. valid 데이터 표준화
# ==========================================================
# transform(): fit()에서 계산한 평균과 표준편차를 사용해 전달받은 데이터를 표준화함.
#
# 표준화 공식:
#
# (원래 값 - train 평균) / train 표준편차
#
# valid = [400, 500]
#
# 중요한 점: valid의 평균을 새로 계산하지 않음! 반드시 train에서 계산한 기준을 사용함.
#
# 반환값:
# NumPy ndarray 형태의 표준화된 데이터
# 완료 B04-1: scaler의 transform으로 valid를 변환하세요.
valid_ready = scaler.transform(valid)



# ==========================================================
# 6. 결과 출력
# ==========================================================
# scaler.mean_:
# fit()에서 계산한 각 열의 평균을 저장한 속성
#
# .tolist():
# NumPy 배열을 일반 Python List로 변환함.
#
# 출력 결과: [200.0]
print("train에서 배운 평균:", scaler.mean_.tolist())
# valid_ready:
# transform()의 반환값인 NumPy ndarray
#
# .round(3):
# 배열의 각 숫자를 소수점 셋째 자리까지 반올림함.
#
# 원본 배열을 수정하지 않고 반올림된 배열을 반환함.
print("valid 변환 결과:")
print(valid_ready.round(3))
