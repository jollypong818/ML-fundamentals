"""
실습 05: 원-핫 인코딩(One-Hot Encoding)

목적:
문자열로 된 범주형 데이터를 0과 1로 변환하기.

왜 필요한가?
머신러닝 모델 중에는 문자열을 직접 입력받지 못하고 숫자 형태의 데이터만 처리하는 모델이 많기 때문임.

예를 들어:
"qa"      → [1, 0]
"summary" → [0, 1]

이처럼 각 범주를 서로 다른 열로 표현하는 방법을 원-핫 인코딩(One-Hot Encoding)이라고 함.
"""

# ==========================================================
# 1. 필요한 라이브러리 가져오기
# ==========================================================
# sklearn.preprocessing:
# 머신러닝에 사용할 데이터를 변환하는 기능을 제공하는 모듈
#
# OneHotEncoder:
# 문자열 등의 범주형 데이터를 0과 1로 변환하는 클래스
#
# 예를 들어 작업 유형이 qa, summary라면
# 각각의 작업 유형을 별도의 숫자 열로 표현할 수 있음.
from sklearn.preprocessing import OneHotEncoder



# ==========================================================
# 2. 학습용(train), 검증용(valid) 데이터 생성
# ==========================================================
# train:
# 인코딩 규칙을 학습할 데이터
#
# "qa"      = 질문과 답변 작업
# "summary" = 요약 작업
#
# 왜 리스트가 두 겹인가?
# sklearn은 입력 데이터를 기본적으로 (행 개수, 열 개수) 형태의 2차원 데이터로 받기 때문임.
#
# [["qa"], ["summary"], ["qa"]] → 3행 1열 데이터
#
# 안쪽 리스트 하나가 데이터의 한 행을 의미함.
train = [["qa"], ["summary"], ["qa"]]

# valid:
# 학습하지 않은 별도의 검증 데이터
#
# 2행 1열 데이터
#
# train에서 학습한 인코딩 규칙을 적용할 예정임.
valid = [["summary"], ["qa"]]

# ==========================================================
# 3. OneHotEncoder 객체 생성
# ==========================================================

# OneHotEncoder():
# 범주형 데이터를 숫자로 변환하는 인코더 객체 생성
#
# sparse_output=False:
# 결과를 희소 행렬(sparse matrix)이 아닌 일반 NumPy 배열(ndarray)로 반환하도록 설정함.
#
# 희소 행렬이란?
# 값이 대부분 0인 데이터를 효율적으로 저장하는 자료구조임.
#
# 지금은 결과를 쉽게 확인하기 위해 False를 사용함.
#
# 주의: 객체를 생성했다고 바로 데이터가 변환되는 것은 아님.
encoder = OneHotEncoder(sparse_output=False)

# ==========================================================
# 4. train 데이터로 인코딩 규칙 학습
# ==========================================================
# fit():
# train 데이터에 어떤 범주들이 존재하는지 확인하고 저장함.
#
# train = [["qa"], ["summary"], ["qa"]]
#
# 여기서 발견한 범주:
# qa
# summary
#
# 기본 설정에서는 범주를 정렬하므로 열 순서는 다음과 같음.
#
# 첫 번째 열 = qa
# 두 번째 열 = summary
#
# 따라서:
#
# qa      → [1, 0]
# summary → [0, 1]
#
# fit()은 규칙을 학습할 뿐, 실제 데이터를 변환해서 반환하지는 않음.
encoder.fit(train)


# ==========================================================
# 5. valid 데이터를 원-핫 인코딩
# ==========================================================

# transform(valid):
# fit()에서 학습한 범주와 열 순서를 기준으로 valid 데이터를 숫자로 변환함.
#
# valid = [["summary"], ["qa"]]
#
# 변환 결과:
#
# summary → [0.0, 1.0]
# qa      → [1.0, 0.0]
#
# transform()의 반환값은 NumPy ndarray임.
#
# .tolist():
# NumPy 배열을 일반 Python 리스트로 변환함.
#
# 왜 다시 fit하지 않는가?
# train에서 학습한 열 구조를 그대로 유지해야 머신러닝 모델에 일관된 입력을 전달할 수 있기 때문임.
# 완료 - B05-1: encoder.transform(valid).tolist()로 실제 변환 결과를 구하세요.
valid_ready = encoder.transform(valid).tolist()


# ==========================================================
# 6. 학습한 열 순서 확인
# ==========================================================
# encoder.categories_:
# fit()에서 학습한 범주 목록을 저장한 속성
#
# 열이 여러 개라면 각 입력 열의 범주 목록이 들어 있음.
#
# categories_[0]:
# 첫 번째 입력 열의 범주 목록을 가져옴.
#
# 여기서는 입력 열이 하나뿐이므로 [0]을 사용함.
#
# .tolist():
# NumPy 배열을 Python 리스트로 변환함.
#
# 출력:
# ['qa', 'summary']
print("열 순서:", encoder.categories_[0].tolist())

# ==========================================================
# 7. 변환 결과 출력
# ==========================================================

# valid_ready에는 변환된 숫자 데이터가 저장되어 있음.
#
# 출력:
# [[0.0, 1.0], [1.0, 0.0]]
print("valid 변환:", valid_ready)
