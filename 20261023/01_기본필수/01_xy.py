"""01 기본필수: CSV에서 입력과 정답을 각각 꺼냅니다."""

# ==========================================================
# 1. 필요한 라이브러리 가져오기
# ==========================================================

# 모듈에서 path 클래스를 가져옴, 현재 python 파일과 같은 폴더에 있는 CSV 파일을 찾는데 사용
from pathlib import Path
# CSV 데이터를 표(dataframe) 형태로 불러오고, 필요한 열을 선택하거나 데이터를 분석하는 목적
import pandas as pd



# ==========================================================
# 2. CSV 파일을 읽어서 DataFrame 생성
# ==========================================================

# 제공: 이 Python 파일과 같은 폴더에 있는 CSV를 읽습니다. 작업 폴더를 바꾸어도 됩니다.
# 현재 실행중인 python 파일의 폴더경로를 가져옴 
HERE = Path(__file__).resolve().parent

"""
pandas read_csv()를 사용해 CSV파일 read 후 data 변수에 저장
CSV 파일은 텍스트파일이지만 Pandas로 읽으면 행과 열을 가진 DataFrame으로 변환
"""
data = pd.read_csv(HERE / "requests.csv")



# ==========================================================
# 3. 머신러닝 모델에 사용할 입력 데이터(X) 생성
# ==========================================================
"""
머신러닝에서는 일반적으로 x = 입력데이터(feature, 특성)
y = 정답데이터(Label, Target) 라는 변수명을 사용
이 실습의 목적은 요청이 실패할지 예측하는것
예측에 사용할 정보: input_chars(입력된 글자수), task_type(요청작업유형)
예측할 정답: failed(요청실패여부 0:성공, 1:실패)
"""
# X는 예측 전에 알 수 있는 정보입니다. ID와 정답은 입력에 넣지 않습니다.
# 완료 - B01-1: 입력 열을 input_chars와 task_type 두 개로 바꾸세요.
# 대괄호가 두 개인 이유:
# 안쪽 [] = 선택할 열 이름들을 담은 List
# 바깥쪽 [] = DataFrame에서 해당 열들을 조회
# 결과 X는 2차원 DataFrame임.
X = data[["input_chars", "task_type"]]


# ==========================================================
# 4. 머신러닝 모델이 맞혀야 할 정답(y) 생성
# ==========================================================

# 완료- B01-2: 정답 열 failed를 선택하세요. 0은 성공, 1은 실패입니다.
# failed 열만 추출함.
#
# 0 = 성공
# 1 = 실패
#
# 왜 따로 추출하는가?
# 머신러닝 모델은 X를 입력받아 y를 예측하도록 학습하기 때문임.
#
# data["failed"]
# → 열 하나를 선택하므로 Pandas Series가 반환됨.
#
# Series란?
# Pandas에서 사용하는 1차원 데이터 구조임.
#
# DataFrame = 2차원 표
# Series    = 1차원 데이터
y = data["failed"]


# ==========================================================
# 5. 데이터가 제대로 분리되었는지 확인
# ==========================================================
# X.columns
# → DataFrame의 열 이름들을 가져옴.
#
# .tolist()
# → Pandas의 Index 객체를 일반 Python List로 변환함.
#
# 왜 확인하는가?
# 모델에 전달할 입력 열이 정확히 선택되었는지 확인하기 위해서임.
print("입력 열:", X.columns.tolist())

# X.shape
# → DataFrame의 행과 열 개수를 반환함.
#
# 예: (100, 2)
# 100 = 요청 데이터 100건
# 2   = 입력 변수 2개
#
# 왜 확인하는가?
# 학습에 사용할 데이터의 크기와 구조를 파악하기 위해서임.
print("X 모양:", X.shape)


# y.shape
# → 정답 데이터의 크기를 반환함.
#
# 예: (100,)
# 정답이 100개인 1차원 데이터라는 뜻임.
#
# 왜 확인하는가?
# X의 행 개수와 y의 데이터 개수가 일치해야 하기 때문임.
#
# X가 100행이라면 y에도 정답이 100개 있어야 함.
print("y 모양:", y.shape)

# y.head(3)
# → 정답 데이터의 처음 3개를 가져옴.
#
# .tolist()
# → 가져온 Series를 일반 Python List로 변환함.
#
# 왜 확인하는가?
# 정답 데이터가 예상한 대로 0과 1로 구성되어 있는지
# 일부 데이터를 출력해 확인하기 위해서임.
#
# 예: [0, 1, 0]
print("처음 3개 정답:", y.head(3).tolist())
