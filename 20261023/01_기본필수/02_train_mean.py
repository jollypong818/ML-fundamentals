"""02 기본필수: 평균을 어디에서 계산해야 하는지 비교합니다."""
# ==========================================================
# 1. 학습 데이터(train)와 검증 데이터(valid) 준비
# ==========================================================
# train_values = 학습 데이터
# 머신러닝 모델이 학습할 때 사용하는 데이터
train_values = [10, 20]

# valid_values = 검증 데이터
# 학습한 모델이 새로운 데이터에서도 잘 작동하는지 평가하기 위해 따로 보관한 데이터
#
# 왜 분리하는가?
# 학습에 사용하지 않은 데이터로 평가해야 모델의 실제 예측 성능을 확인할 수 있기 때문
valid_values = [100]


# ==========================================================
# 2. 학습 데이터의 평균 계산 (정답)
# ==========================================================
# 진짜 학습 기준으로 사용할 수 있는 것은 train의 평균입니다.
# 완료 B02-1: train_values의 합을 개수로 나누세요.

# 데이터 전처리에서 평균이 필요한 이유:
# 예를 들어 데이터의 평균을 빼서 값을 변환하는 평균 중심화(mean centering)에 사용할 수 있음.
#
# 왜 train의 평균만 구하는가?
# 검증 데이터의 정보를 학습 과정에 사용하면 데이터 누수(Data Leakage)가 발생할 수 있기 때문
#
# sum(train_values)
# → 리스트에 들어 있는 숫자의 합계를 반환함.
# → 10 + 20 = 30
#
# len(train_values)
# → 리스트에 들어 있는 원소 개수를 반환함.
# → 2
#
# 평균 = 합계 / 개수
# → 30 / 2 = 15.0
#
# 따라서 학습 데이터의 평균은 15.0임.
train_mean = sum(train_values) / len(train_values)


# ==========================================================
# 3. 전체 데이터의 평균 계산 (잘못된 기준 비교용)
# ==========================================================
# 아래 전체 평균은 '잘못된 기준과의 비교'를 위한 시연일 뿐입니다.


# 리스트의 + 연산자는 숫자를 더하는 것이 아니라 두 리스트를 연결해서 새로운 리스트를 생성함.
#
# [10, 20] + [100]
# → [10, 20, 100]
#
# 여기에는 학습 데이터뿐만 아니라 검증 데이터까지 포함되어 있음.
all_values = train_values + valid_values

# 전체 데이터의 평균을 계산
#
# sum(all_values)
# → 10 + 20 + 100 = 130
#
# len(all_values)
# → 3
#
# 130 / 3 = 43.333...
#
# 문제점:
# 검증 데이터 100이 평균 계산에 영향을 주었음.
# 이 평균을 학습 전처리의 기준으로 사용하면 검증 데이터의 정보가 학습 과정에 유입됨.
# 따라서 실제 학습 전처리에는 사용하면 안 됨.
all_mean = sum(all_values) / len(all_values)


# ==========================================================
# 4. 평균 출력 및 비교
# ==========================================================
# round(숫자, 2) → 숫자를 소수점 둘째 자리까지 반올림함.
print("train 평균:", round(train_mean, 2))

# 검증 데이터가 포함되었기 때문에 학습 데이터만 사용했을 때와 평균이 크게 달라짐.
print("전체 평균(비교만):", round(all_mean, 2))
# 머신러닝 전처리의 핵심 규칙:
# 평균, 표준편차 등 학습으로 결정하는 전처리 기준은 train 데이터에서만 계산해야 함.
# 검증 데이터에는 train에서 구한 기준을 그대로 적용함.
print("실제 전처리에는 train 평균만 사용합니다.")
